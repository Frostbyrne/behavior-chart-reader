/** The app mark: a tiny rating grid. */
export function Mark({ className = "" }: { className?: string }) {
  return (
    <svg viewBox="0 0 32 32" className={className} aria-hidden>
      <rect width="32" height="32" rx="8" fill="#1f2a44" />
      {[
        ["#5fc48a", 7, 7],
        ["#5fc48a", 13.5, 7],
        ["#f6c945", 20, 7],
        ["#5fc48a", 7, 13.5],
        ["#ef7d70", 13.5, 13.5],
        ["#5fc48a", 20, 13.5],
        ["#5fc48a", 7, 20],
        ["#5fc48a", 13.5, 20],
        ["#5fc48a", 20, 20],
      ].map(([fill, x, y], i) => (
        <rect key={i} x={x as number} y={y as number} width="5" height="5" rx="1.4" fill={fill as string} />
      ))}
    </svg>
  );
}
